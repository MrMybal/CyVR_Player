"""Compile the English message IDs and French catalogue; no runtime JSON dependency."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    messages=json.loads((ROOT/'assets/locales/fr.json').read_text(encoding='utf-8'))
    lines=['// Generated by tools/generate_player_locales.py. English is the default.','#pragma once','#include <string_view>','namespace cyvr::player {','struct PlayerMessage { std::string_view english, french; };','inline constexpr PlayerMessage player_messages[] = {']
    for english,french in sorted(messages.items()):
        assert isinstance(french,str) and french and english
        lines.append('    {'+json.dumps(english,ensure_ascii=False)+', '+json.dumps(french,ensure_ascii=False)+'},')
    lines+=['};','}',''];text='\n'.join(lines)
    path=ROOT/'include/cyvr/player/locale_data.hpp'
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8')!=text:raise SystemExit('Player locale table is stale')
    elif not path.exists() or path.read_text(encoding='utf-8')!=text:path.write_text(text,encoding='utf-8')
    print(f'{len(messages)} English/French player messages checked')
if __name__=='__main__':main()
