"""Reproducible GLSL 450 wrapper around the pinned BSD-3-Clause GSR 1 kernel.

The algorithm stays upstream. Replace entry point, I/O and texture intrinsics
to sample an isolated packed eye in perceptual RGB, then return linear RGB.
"""
import argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    source=(ROOT/'third_party/gsr1/sgsr1_shader_mobile.frag').read_text(encoding='utf-8')
    body=source[source.index('float fastLanczos2'):]
    body=body.replace('void main()','vec3 GsrFilter(vec2 texcoord)')
    body=body.replace('in_TEXCOORD0.xy','texcoord').replace('in_TEXCOORD0.x','texcoord.x').replace('in_TEXCOORD0.y','texcoord.y')
    body=body.replace('int mode = OperationMode;', 'vec4 ViewportInfo[1]=vec4[](vec4(1./vec2(eyeSize),vec2(eyeSize)));\n\tint mode = OperationMode;')
    body=body.replace('out_Target0.xyzw = color;','return linearize(color.xyz);')
    text='''// Generated by tools/adapt_gsr1.py; see third_party/gsr1/LICENSE.
// Copyright (c) 2025, Qualcomm Innovation Center, Inc. All rights reserved.
// SPDX-License-Identifier: BSD-3-Clause
vec4 gsrTextureLod(sampler2D ignored,vec2 p,float lod){
    vec2 coord=(vec2(origin)+clamp(p*vec2(eyeSize),vec2(.5),vec2(eyeSize)-.5))/vec2(pc.dimensions.xy);
    return vec4(perceptual(textureLod(source_image,coord,0.).rgb),1);
}
vec4 gsrTextureGather(sampler2D ignored,vec2 p,int channel){return gatherChannel(p,channel);}
#define OperationMode 1
#define EdgeThreshold (4.0/255.0)
#define EdgeSharpness mix(1.0,2.0,pc.view.w)
#define ps0 source_image
#define textureLod gsrTextureLod
#define textureGather gsrTextureGather
'''+body+'''
#undef OperationMode
#undef EdgeThreshold
#undef EdgeSharpness
#undef ps0
#undef textureLod
#undef textureGather
'''
    # Desktop GLSL has no precision qualifiers on constructor expressions.
    text=text.replace('highp ','')
    path=ROOT/'shaders/gsr1.glsl'
    if args.check:
        if path.read_text(encoding='utf-8')!=text:raise SystemExit('GSR wrapper is stale')
    else:path.write_text(text,encoding='utf-8')
    print('Pinned GSR 1 wrapper checked')
if __name__=='__main__':main()
